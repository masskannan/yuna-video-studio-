import json, os, sys, urllib.request, urllib.parse

def main():
    cid, csec, rtok = os.getenv("YOUTUBE_CLIENT_ID"), os.getenv("YOUTUBE_CLIENT_SECRET"), os.getenv("YOUTUBE_REFRESH_TOKEN")
    video_path = sys.argv[1] if len(sys.argv) > 1 else "final/final_movie.mp4"
    if not (cid and csec and rtok):
        print("YOUTUBE SKIP: missing OAuth env (dry-run OK)")
        return
    if not os.path.exists(video_path):
        print(f"YOUTUBE SKIP: missing {video_path}")
        return
    body = urllib.parse.urlencode({"client_id": cid, "client_secret": csec, "refresh_token": rtok, "grant_type": "refresh_token"}).encode()
    tok = json.loads(urllib.request.urlopen(urllib.request.Request("https://oauth2.googleapis.com/token", data=body), timeout=20).read())["access_token"]
    meta = json.dumps({"snippet": {"title": "YUNA Studio Video", "description": "Generated by YUNA Cloud Video Studio", "categoryId": "22"}, "status": {"privacyStatus": "private"}}).encode()
    req = urllib.request.Request("https://www.googleapis.com/upload/youtube/v3/videos?uploadType=resumable&part=snippet,status", data=meta, headers={"Authorization": f"Bearer {tok}", "Content-Type": "application/json; charset=UTF-8", "X-Upload-Content-Type": "video/mp4"})
    res = urllib.request.urlopen(req, timeout=30)
    up_url = res.headers["Location"]
    with open(video_path, "rb") as vf:
        up = urllib.request.urlopen(urllib.request.Request(up_url, data=vf.read(), method="PUT", headers={"Content-Type": "video/mp4"}), timeout=120)
    print("YOUTUBE UPLOADED:", json.loads(up.read()).get("id"))

if __name__ == "__main__":
    main()
